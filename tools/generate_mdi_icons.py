"""Rasterise pinned MDI glyphs (Apache-2.0, assets/icons/mdi) to native 1-bit masks.

Same light-mask pipeline as the historical 0.7.0-0.7.4 MDI weather symbols (see
assets/icons/mdi/SOURCE.md): fill the unmodified SVG path at 4x, inset the black
boundary by 0.5 SVG units, box-downsample once and threshold at 50 %. No runtime scaling.
"""
from pathlib import Path
import hashlib, json, sys, xml.etree.ElementTree as ET
from fontTools.pens.basePen import BasePen
from fontTools.svgLib.path import parse_path
from PIL import Image, ImageDraw, ImageFilter
ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/icons/mdi'
OUT = ROOT / 'firmware/InkOS/src/MdiIconsData.h'
GLYPHS = {'aurora': 'F1BB9'}  # name -> MDI codepoint
SIZES = [40, 64]              # the native sizes of the existing MDI masks
SCALE, INSET = 4, 0.5

class FillPen(BasePen):
    def __init__(self): super().__init__(None); self.contours = []; self.path = []
    def _moveTo(self, p): self._flush(); self.path = [p]
    def _lineTo(self, p): self.path.append(p)
    def _curveToOne(self, a, b, c):
        p = self.path[-1]
        for i in range(1, 33):
            t = i / 32; u = 1 - t
            self.path.append(tuple(u*u*u*p[k] + 3*u*u*t*a[k] + 3*u*t*t*b[k] + t*t*t*c[k] for k in (0, 1)))
    def _qCurveToOne(self, a, b):
        p = self.path[-1]
        for i in range(1, 33):
            t = i / 32; u = 1 - t
            self.path.append(tuple(u*u*p[k] + 2*u*t*a[k] + t*t*b[k] for k in (0, 1)))
    def _closePath(self): self._flush()
    def _endPath(self): self._flush()
    def _flush(self):
        if len(self.path) > 2: self.contours.append(self.path)
        self.path = []

def raster(name, size):
    pen = FillPen()
    for e in ET.fromstring((ASSETS / f'{name}.svg').read_bytes()):
        if e.tag.rsplit('}', 1)[-1] == 'path': parse_path(e.attrib['d'], pen)
    pen._flush()
    big = size * SCALE; f = big / 24
    mask = Image.new('L', (big, big), 0)
    for contour in pen.contours:  # single-contour glyphs: plain fill is exact
        ImageDraw.Draw(mask).polygon([(x * f, y * f) for x, y in contour], fill=255)
    k = 2 * round(INSET * f) + 1
    mask = mask.filter(ImageFilter.MinFilter(k))
    small = mask.resize((size, size), Image.Resampling.BOX)
    return small.point(lambda p: 0 if p >= 128 else 255, mode='1')  # black ink = 0

def main():
    lines = ['// Generated by tools/generate_mdi_icons.py from pinned Material Design Icons 7.4.47',
             '// (Apache-2.0, assets/icons/mdi/LICENSE). Canvas::image layout: 0 = ink, MSB first.',
             '#pragma once', '#include <stdint.h>', 'namespace ink::mdi_assets {']
    manifest = json.loads((ASSETS / 'manifest.json').read_text())
    for name in GLYPHS:
        manifest['sha256'][name] = hashlib.sha256((ASSETS / f'{name}.svg').read_bytes()).hexdigest()
        for size in SIZES:
            img = raster(name, size)
            ink = img.tobytes()
            assert len(ink) == size * size // 8
            lines.append(f'static const uint8_t {name.replace("-", "_")}_{size}[] = {{' + ','.join(map(str, ink)) + '};')
            if '--preview' in sys.argv: img.save(f'/tmp/mdi-{name}-{size}.png')
    lines += ['} // namespace ink::mdi_assets', '']
    OUT.write_text('\n'.join(lines))
    manifest['derived_glyphs'] = {n: {'codepoint': c, 'native_sizes': SIZES} for n, c in GLYPHS.items()}
    (ASSETS / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print('Generated', len(GLYPHS), 'MDI glyph(s) at', SIZES)

if __name__ == '__main__': main()
